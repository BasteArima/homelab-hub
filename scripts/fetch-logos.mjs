// Downloads the dashboard-icons SVG set into public/logos and regenerates
// src/lib/logos.generated.ts (slug list + alias→slug map for auto-matching).
// Runs at Docker build time (see Dockerfile) and can be run locally for dev:
//   node scripts/fetch-logos.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "logos");
const MANIFEST = path.join(ROOT, "src", "lib", "logos.generated.ts");
const REPO = "https://cdn.jsdelivr.net/gh/homarr-labs/dashboard-icons";
const CONCURRENCY = 24;

function slugify(s) {
  return s
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function main() {
  const tree = await (await fetch(`${REPO}/tree.json`)).json();
  const slugs = tree.svg.map((f) => f.replace(/\.svg$/, "")).sort();
  console.log(`Downloading ${slugs.length} SVG logos…`);

  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });

  let done = 0;
  const queue = [...slugs];
  async function worker() {
    for (let slug = queue.pop(); slug; slug = queue.pop()) {
      const res = await fetch(`${REPO}/svg/${slug}.svg`);
      if (res.ok) {
        fs.writeFileSync(path.join(OUT_DIR, `${slug}.svg`), await res.text());
      }
      if (++done % 250 === 0) console.log(`  ${done}/${slugs.length}`);
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  // Build alias → slug map from metadata (e.g. "omv" → "openmediavault").
  const aliasMap = {};
  try {
    const meta = await (await fetch(`${REPO}/metadata.json`)).json();
    for (const [slug, info] of Object.entries(meta)) {
      for (const alias of info.aliases ?? []) {
        const a = slugify(alias);
        if (a && !slugs.includes(a) && !aliasMap[a]) aliasMap[a] = slug;
      }
    }
  } catch {
    console.warn("metadata.json fetch failed — skipping aliases");
  }

  const header = "// Auto-generated by scripts/fetch-logos.mjs — do not edit by hand.\n";
  fs.writeFileSync(
    MANIFEST,
    `${header}export const LOGO_SLUGS: readonly string[] = ${JSON.stringify(slugs)};\n\n` +
      `export const LOGO_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliasMap)};\n`,
  );
  console.log(`Done: ${slugs.length} logos, ${Object.keys(aliasMap).length} aliases.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
